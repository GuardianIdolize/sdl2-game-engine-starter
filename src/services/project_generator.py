"""Project generator.

Scaffolds a new engine project from an `EngineProfile`. Dispatches to the
per-subsystem handlers, writes the CMakeLists, and records a manifest.
"""

from __future__ import annotations

import shutil
from pathlib import Path

from src import __version__
from src.core.engine_manifest import EngineManifest
from src.core.engine_profile import EngineProfile
from src.handlers.input_handler import InputHandler
from src.handlers.render_handler import RenderHandler
from src.handlers.scene_handler import SceneHandler

DEFAULT_TEMPLATE = """\
[engine]
name = "mygame"
platform = "windows"
cxx_standard = 17
sdl2_min = "2.28.0"
render_backend = "opengl"
modules = ["render", "input", "scene", "audio"]
"""

CMAKE_TEMPLATE = """\
cmake_minimum_required(VERSION 3.24)
project({name} LANGUAGES CXX)

set(CMAKE_CXX_STANDARD {cxx_standard})
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_EXPORT_COMPILE_COMMANDS ON)

find_package(SDL2 {sdl2_min} REQUIRED)

add_executable({name}_game
    src/engine_cpp/main.cpp
    src/engine_cpp/render/renderer.cpp
    src/engine_cpp/input/input_state.cpp
    src/engine_cpp/scene/scene_stack.cpp
)

target_include_directories({name}_game PRIVATE src/engine_cpp)
target_link_libraries({name}_game PRIVATE SDL2::SDL2 SDL2::SDL2main)
"""

MAIN_TEMPLATE = """\
// {name} — entry point. Generated by sdl2-game-engine-starter.
#include "render/renderer.h"
#include "input/input_state.h"
#include "scene/scene_stack.h"
#include <SDL.h>
#include <chrono>
#include <stdexcept>

int main(int, char**) {{
    if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_TIMER) != 0)
        throw std::runtime_error(SDL_GetError());

    SDL_Window* win = SDL_CreateWindow(
        "{name}", SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED,
        1280, 720, SDL_WINDOW_RESIZABLE);
    if (!win) throw std::runtime_error(SDL_GetError());

    {ns}::render::Renderer renderer(win, {ns}::render::Backend::OpenGL);
    {ns}::input::InputState input;
    {ns}::scene::SceneStack scenes;

    auto prev = std::chrono::steady_clock::now();
    while (!input.quit_requested()) {{
        input.pump();
        auto now = std::chrono::steady_clock::now();
        double dt = std::chrono::duration<double>(now - prev).count();
        prev = now;

        renderer.begin_frame();
        scenes.update(dt);
        scenes.render(renderer);
        renderer.end_frame();
    }}

    SDL_DestroyWindow(win);
    SDL_Quit();
    return 0;
}}
"""


class ProjectGenerator:
    """Generates a fresh engine project directory tree."""

    def __init__(self, template: str = "default") -> None:
        self.template = template

    def generate(self, target: Path, *, force: bool = False) -> Path:
        if target.exists() and any(target.iterdir()) and not force:
            raise FileExistsError(f"{target} exists and is not empty; pass force=True to overwrite")
        if force and target.exists():
            shutil.rmtree(target)
        target.mkdir(parents=True, exist_ok=True)

        (target / "engine.toml").write_text(DEFAULT_TEMPLATE, encoding="utf-8")
        profile = EngineProfile.load(target / "engine.toml")

        manifest = EngineManifest(target)
        emitted: list[Path] = []
        for handler in (
            RenderHandler(profile),
            InputHandler(profile),
            SceneHandler(profile),
        ):
            emitted.extend(handler.emit(target))

        ns = profile.name.replace("-", "_").lower()
        main_cpp = target / "src" / "engine_cpp" / "main.cpp"
        main_cpp.parent.mkdir(parents=True, exist_ok=True)
        main_cpp.write_text(MAIN_TEMPLATE.format(name=profile.name, ns=ns), encoding="utf-8")
        emitted.append(main_cpp)

        cmake = target / "CMakeLists.txt"
        cmake.write_text(
            CMAKE_TEMPLATE.format(
                name=profile.name,
                cxx_standard=profile.cxx_standard,
                sdl2_min=profile.sdl2_min,
            ),
            encoding="utf-8",
        )
        emitted.append(cmake)

        for path in emitted:
            manifest.record(path, __version__)
        manifest.write()
        return target