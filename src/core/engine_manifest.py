"""Engine manifest: the on-disk record of a generated project.

Written to `.sdl2_starter/engine_manifest.toml` inside a generated project.
Records every file the generator emitted plus a content hash so `sdl2-starter
build` can detect hand-edits that would be clobbered by a re-scaffold.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from pathlib import Path

MANIFEST_DIR = ".sdl2_starter"
MANIFEST_NAME = "engine_manifest.toml"


@dataclass(frozen=True, slots=True)
class ManifestEntry:
    relpath: str
    sha256: str
    generator_version: str


def hash_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


class EngineManifest:
    """Mutable collection of manifest entries for one project."""

    def __init__(self, project_root: Path) -> None:
        self.project_root = project_root
        self.entries: dict[str, ManifestEntry] = {}

    def record(self, path: Path, generator_version: str) -> None:
        rel = path.relative_to(self.project_root).as_posix()
        self.entries[rel] = ManifestEntry(rel, hash_file(path), generator_version)

    def drifted(self, path: Path) -> bool:
        """True if `path` exists and its hash differs from the recorded one."""
        rel = path.relative_to(self.project_root).as_posix()
        entry = self.entries.get(rel)
        if entry is None or not path.exists():
            return False
        return hash_file(path) != entry.sha256

    def write(self) -> Path:
        out_dir = self.project_root / MANIFEST_DIR
        out_dir.mkdir(parents=True, exist_ok=True)
        out = out_dir / MANIFEST_NAME
        lines = ["# generated by sdl2-game-engine-starter — do not edit by hand", ""]
        for entry in sorted(self.entries.values(), key=lambda e: e.relpath):
            lines.append("[[files]]")
            lines.append(f'path = "{entry.relpath}"')
            lines.append(f'sha256 = "{entry.sha256}"')
            lines.append(f'generator = "{entry.generator_version}"')
            lines.append("")
        out.write_text("\n".join(lines), encoding="utf-8")
        return out